from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit

from PIL import Image
from playwright.sync_api import sync_playwright

EXP = Path(__file__).resolve().parent
DEFAULT_OUT = EXP / "evidencias" / "transferencias-fixture"
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"

BOOT = """async revision => {
  window.transferEvents=[];
  navigator.serviceWorker.addEventListener('message',event=>{
    if(event.data?.type==='LIV_TRANSFER_STATE')transferEvents.push(event.data.state);
  });
  const registration=await navigator.serviceWorker.register('transfer-worker.js?revision='+revision,{scope:'./'});
  await navigator.serviceWorker.ready;
  const deadline=performance.now()+15000;
  while(!navigator.serviceWorker.controller?.scriptURL.includes('revision='+revision)){
    if(performance.now()>deadline)throw Error('Fixture worker did not claim this page.');
    await new Promise(resolve=>setTimeout(resolve,20));
  }
  window.transferCommand=(command,group)=>new Promise((resolve,reject)=>{
    const channel=new MessageChannel();
    const timer=setTimeout(()=>reject(Error('Transfer command timed out: '+command)),15000);
    channel.port1.onmessage=event=>{
      clearTimeout(timer);channel.port1.close();
      resolve(event.data);
    };
    navigator.serviceWorker.controller.postMessage({type:'LIV_TRANSFER',command,...(group?{group}:{})},[channel.port2]);
  });
  return {controlled:true,scriptURL:navigator.serviceWorker.controller.scriptURL};
}"""


def sha(body: bytes) -> str:
    return hashlib.sha256(body).hexdigest()


def png() -> bytes:
    output = io.BytesIO()
    Image.new("RGB", (8, 8), (39, 142, 94)).save(output, format="PNG")
    return output.getvalue()


def html(name: str) -> bytes:
    return (f'<!doctype html><meta charset="utf-8"><p id="fixture-ready">{name}</p>'
            + "<!--" + name * 4096 + "-->").encode()


class Fixture:
    def __init__(self):
        self.lock = threading.Lock()
        self.resources: dict[str, bytes] = {}
        self.manifest: dict = {}
        self.requests: list[dict] = []
        self.gates: dict[str, threading.Event] = {}
        self.revision = 0

    def configure(self, name: str, *, wrong_hash: bool = False, replacement: bool = False):
        suffix = "replacement" if replacement else name
        paths = {
            "tour": f"site-baseline/{name}-tour.html",
            "map": f"site-baseline/{name}-map.html",
            "map-model": f"site-baseline/{name}-map.glb",
            "map-detail": f"site-baseline/{name}-map.bin",
            "planta2d": f"plantas2d/{name}-planta.png",
        }
        bodies = {
            paths["tour"]: html("tour-" + suffix),
            paths["map"]: html("map-" + suffix),
            paths["map-model"]: ("model-" + suffix).encode() * 2048,
            paths["map-detail"]: ("tile-" + suffix).encode() * 2048,
            paths["planta2d"]: png(),
        }
        records = [{"path": path, "group": "map" if key in ["map-detail", "map-model"] else key,
                    "bytes": len(bodies[path]), "sha256": sha(bodies[path]),
                    "essential": key != "map-detail"}
                   for key, path in paths.items()]
        if wrong_hash:
            records[0]["sha256"] = "0" * 64
        version = sha(json.dumps(records, sort_keys=True).encode())
        manifest = {"schema": "liv-transfer-manifest-v1", "version": version,
                    "order": ["tour", "map", "planta2d"],
                    "groups": {"tour": {"label": "Tour 3D"}, "map": {"label": "Mapa"},
                               "planta2d": {"label": "Planta 2D"}}, "files": records}
        with self.lock:
            self.resources.update({"/fixture/" + path: body for path, body in bodies.items()})
            self.manifest = manifest
            self.revision += 1
        return paths, bodies, manifest

    def hold(self, relative: str):
        event = threading.Event()
        self.gates["/fixture/" + relative] = event
        return event

    def started(self, relative: str):
        with self.lock:
            return [dict(item) for item in self.requests if item["path"] == "/fixture/" + relative]

    def snapshot(self):
        with self.lock:
            return [dict(item) for item in self.requests]


def serve(fixture: Fixture):
    class Handler(BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.1"

        def log_message(self, *_):
            pass

        def handle(self):
            try:
                super().handle()
            except (BrokenPipeError, ConnectionResetError, ConnectionAbortedError):
                pass

        def do_GET(self):
            path = urlsplit(self.path).path
            if path in ["/", "/fixture/", "/fixture/index.html"]:
                body, content_type = b'<!doctype html><meta charset="utf-8"><title>Transfer fixture</title>', "text/html"
            elif path == "/fixture/transfer-worker.js":
                hook = b"""const fixtureMatch=Cache.prototype.match;
Cache.prototype.match=async function(request,options){
 if(self.__fixtureDelayMatch&&String(request?.url||request).endsWith('/lookup-race-tour.html')){
  await (await fetch(new URL('match-gate',self.registration.scope))).arrayBuffer();
 }
 return fixtureMatch.call(this,request,options);
};
self.addEventListener('message',event=>{
 if(event.data?.type==='FIXTURE_DELAY_MATCH'){
  self.__fixtureDelayMatch=true;event.ports[0]?.postMessage({ok:true});
 }
});
"""
                body = hook + (EXP / "transfer-worker.js").read_bytes() + f"\n// fixture revision {fixture.revision}\n".encode()
                content_type = "text/javascript"
            elif path == "/fixture/transfer-manifest.json":
                with fixture.lock:
                    body = json.dumps(fixture.manifest).encode()
                content_type = "application/json"
            else:
                with fixture.lock:
                    body = fixture.resources.get(path)
                if body is None:
                    self.send_error(404)
                    return
                content_type = "text/html" if path.endswith(".html") else "image/png" if path.endswith(".png") else "application/octet-stream"
            record = {"path": path, "startedAt": time.monotonic(), "sentBytes": 0,
                      "complete": False, "aborted": False}
            with fixture.lock:
                fixture.requests.append(record)
            self.send_response(200)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(body)))
            # Ensure that cache reuse proved by this test comes from the SW.
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            try:
                self.wfile.write(body[:128])
                self.wfile.flush()
                record["sentBytes"] = min(128, len(body))
                gate = fixture.gates.get(path)
                if gate:
                    gate.wait(30)
                for offset in range(128, len(body), 4096):
                    chunk = body[offset:offset + 4096]
                    self.wfile.write(chunk)
                    self.wfile.flush()
                    record["sentBytes"] += len(chunk)
                record["complete"] = True
            except (BrokenPipeError, ConnectionResetError, ConnectionAbortedError):
                record["aborted"] = True

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    server.daemon_threads = True
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server


def wait_for(predicate, message: str, timeout: float = 15):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        value = predicate()
        if value:
            return value
        time.sleep(.02)
    raise AssertionError(message)


def command(page, action: str, group: str | None = None):
    reply = page.evaluate("([action,group])=>transferCommand(action,group)", [action, group])
    assert reply.get("ok"), reply
    return reply.get("state", {})


def resource_paths(fixture: Fixture, paths: dict):
    expected = {"/fixture/" + path for path in paths.values()}
    return [request["path"] for request in fixture.snapshot() if request["path"] in expected]


def completed(page, fixture: Fixture, manifest: dict):
    return page.evaluate("""async ({version,paths})=>{
      const cache=await caches.open('liv-transfer-'+version);
      return (await Promise.all(paths.map(path=>cache.match(new URL(path,location.href).href)))).every(Boolean);
    }""", {"version": manifest["version"], "paths": [file["path"] for file in manifest["files"]]})


def fetch_body(page, path: str):
    return page.evaluate("""async path=>{
      let response;
      try{response=await fetch(path);}catch(error){return {networkError:String(error)};}
      const body=new Uint8Array(await response.arrayBuffer());
      const hash=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',body))).map(b=>b.toString(16).padStart(2,'0')).join('');
      return {status:response.status,bytes:body.length,sha256:hash};
    }""", path)


def run(out: Path):
    out.mkdir(parents=True, exist_ok=True)
    worker = EXP / "transfer-worker.js"
    if not worker.exists():
        raise RuntimeError("Production transfer-worker.js is not ready. Run only after the owner releases browser QA.")
    fixture = Fixture()
    server = serve(fixture)
    origin = f"http://127.0.0.1:{server.server_port}"
    report = {"recordedAtUtc": datetime.now(timezone.utc).isoformat(), "status": "RUNNING",
              "workerSHA256": sha(worker.read_bytes()), "origin": origin,
              "usesGeneratedFixtures": True, "cacheMatchFaultHook": True, "runsLIVScene": False, "cases": []}
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(executable_path=CHROME, headless=True, args=["--disable-gpu"])

            def setup(name, **options):
                paths, bodies, manifest = fixture.configure(name, **options)
                context = browser.new_context(service_workers="allow")
                page = context.new_page()
                errors = []
                page.on("pageerror", lambda error: errors.append(str(error)))
                page.goto(origin + "/fixture/")
                page.evaluate(BOOT, fixture.revision)
                case = {"name": name, "manifestVersion": manifest["version"], "errors": errors}
                report["cases"].append(case)
                (out / (name + "-manifest.json")).write_text(json.dumps(manifest, indent=2), encoding="utf8")
                return context, page, case, paths, bodies, manifest

            context, page, case, paths, bodies, manifest = setup("order")
            command(page, "start")
            wait_for(lambda: completed(page, fixture, manifest), "Ordered background transfer did not finish.")
            expected = ["/fixture/" + paths[key] for key in ["tour", "map", "map-model", "map-detail", "planta2d"]]
            case["requestOrder"] = resource_paths(fixture, paths)
            assert case["requestOrder"] == expected, case
            command(page, "pause")
            count = len(case["requestOrder"])
            for key, path in paths.items():
                result = fetch_body(page, path)
                assert result == {"status": 200, "bytes": len(bodies[path]), "sha256": sha(bodies[path])}, result
            page.evaluate("""async ({tour,plant})=>{
              const frame=document.createElement('iframe');frame.src=tour;document.body.append(frame);
              await new Promise((resolve,reject)=>{frame.onload=resolve;frame.onerror=reject;});
              if(!frame.contentDocument.querySelector('#fixture-ready'))throw Error('Cached iframe HTML not rendered.');
              const image=new Image();image.src=plant;document.body.append(image);await image.decode();
              if(image.naturalWidth!==8)throw Error('Cached PNG not rendered.');
            }""", {"tour": paths["tour"], "plant": paths["planta2d"]})
            assert len(resource_paths(fixture, paths)) == count, "Repeat/native iframe/image duplicated the network transfer."
            case["repeatNativeCacheHit"] = True
            assert not case["errors"], case
            case["status"] = "PASS"
            context.close()

            context, page, case, paths, bodies, manifest = setup("join")
            gate = fixture.hold(paths["tour"])
            command(page, "start")
            wait_for(lambda: fixture.started(paths["tour"]), "Background tour did not start.")
            page.evaluate("path=>{window.joinedFetch=fetch(path).then(async response=>({status:response.status,bytes:(await response.arrayBuffer()).byteLength}));}", paths["tour"])
            time.sleep(.05)
            assert len(fixture.started(paths["tour"])) == 1, "Foreground fetch started a duplicate background request."
            gate.set()
            result = page.evaluate("()=>joinedFetch")
            assert result == {"status": 200, "bytes": len(bodies[paths["tour"]])}, result
            wait_for(lambda: completed(page, fixture, manifest), "Queue did not continue after joined foreground fetch.")
            command(page, "pause")
            assert len(fixture.started(paths["tour"])) == 1
            case["sameFileNetworkRequests"] = 1
            case["status"] = "PASS"
            context.close()

            context, page, case, paths, bodies, manifest = setup("preempt")
            gate = fixture.hold(paths["tour"])
            command(page, "start")
            wait_for(lambda: fixture.started(paths["tour"]), "Background tour did not start before preemption.")
            page.evaluate("path=>{window.oldDemand=fetch(path).then(()=>({canceled:false})).catch(()=>({canceled:true}));}", paths["tour"])
            command(page, "prioritize", "map")
            assert page.evaluate('()=>oldDemand')["canceled"], "Old foreground demand survived a different selected group."
            result = fetch_body(page, paths["map"])
            assert result["status"] == 200 and result["sha256"] == sha(bodies[paths["map"]]), result
            sequence = resource_paths(fixture, paths)
            assert sequence[0] == "/fixture/" + paths["tour"] and sequence[1] == "/fixture/" + paths["map"], sequence
            gate.set()
            command(page, "resume")
            wait_for(lambda: completed(page, fixture, manifest), "Background queue did not resume after priority group.")
            command(page, "pause")
            case["requestOrder"] = resource_paths(fixture, paths)
            assert len(fixture.started(paths["tour"])) == 2, case
            case["interruptedTourRestartedOnce"] = True
            case["status"] = "PASS"
            context.close()

            context, page, case, paths, bodies, manifest = setup("pause")
            gate = fixture.hold(paths["tour"])
            command(page, "start")
            wait_for(lambda: fixture.started(paths["tour"]), "Tour did not start before pause.")
            state = command(page, "pause")
            assert state["paused"]
            result = fetch_body(page, paths["planta2d"])
            assert result["sha256"] == sha(bodies[paths["planta2d"]])
            time.sleep(.1)
            assert not fixture.started(paths["map"]) and len(fixture.started(paths["tour"])) == 1
            assert command(page, "status")["paused"], "Native demand resumed background queue."
            gate.set()
            command(page, "resume")
            wait_for(lambda: completed(page, fixture, manifest), "Resume did not finish pending resources.")
            assert len(fixture.started(paths["tour"])) == 2
            case["pausedForegroundStillWorks"] = True
            case["status"] = "PASS"
            context.close()

            context, page, case, paths, bodies, manifest = setup("lookup-race")
            tour_gate = fixture.hold(paths["tour"])
            model_gate = fixture.hold(paths["map-model"])
            fixture.resources['/fixture/match-gate'] = b'gate' * 4096
            lookup_gate = fixture.hold('match-gate')
            command(page, "start")
            wait_for(lambda: fixture.started(paths["tour"]), "Lookup race Tour did not start.")
            page.evaluate("""()=>new Promise(resolve=>{
              const channel=new MessageChannel();channel.port1.onmessage=()=>{channel.port1.close();resolve();};
              navigator.serviceWorker.controller.postMessage({type:'FIXTURE_DELAY_MATCH'},[channel.port2]);
            })""")
            page.evaluate("path=>{window.oldDemandResult=null;fetch(path).then(()=>({canceled:false})).catch(()=>({canceled:true})).then(result=>oldDemandResult=result);}", paths["tour"])
            wait_for(lambda: fixture.started('match-gate'), "Old demand did not reach the delayed cache lookup.")
            command(page, "prioritize", "map")
            wait_for(lambda: fixture.started(paths["map-model"]), "Selected map did not start during old cache lookup.")
            lookup_gate.set()
            page.wait_for_function('window.oldDemandResult', timeout=15000)
            assert page.evaluate('oldDemandResult.canceled'), "Canceled old lookup re-entered the transfer queue."
            assert command(page, 'status')['active']['path'] == paths['map-model']
            assert len(fixture.started(paths['map-model'])) == 1
            model_gate.set();tour_gate.set()
            wait_for(lambda: completed(page, fixture, manifest), "Lookup race queue did not resume.")
            case['lateOldCacheLookupCanceled'] = True
            case['status'] = 'PASS'
            context.close()

            context, page, case, paths, bodies, manifest = setup("integrity", wrong_hash=True)
            command(page, "pause")
            result = fetch_body(page, paths["tour"])
            assert result.get("networkError") or result["status"] >= 400, result
            cached = page.evaluate("async ({version,path})=>!!(await (await caches.open('liv-transfer-'+version)).match(new URL(path,location.href).href))", {"version": manifest["version"], "path": paths["tour"]})
            assert not cached, "A body with the wrong hash was cached."
            case["wrongHashRejectedWithoutCache"] = True
            case["response"] = result
            case["status"] = "PASS"
            context.close()

            context, page, case, paths, bodies, manifest = setup("map-minimum")
            gate = fixture.hold(paths["map-model"])
            command(page, "prioritize", "map")
            wait_for(lambda: fixture.started(paths["map-model"]), "Map model prerequisite did not start.")
            page.evaluate("path=>{window.tileDemand=fetch(path).then(async response=>(await response.arrayBuffer()).byteLength);}", paths["map-detail"])
            time.sleep(.1)
            assert not fixture.started(paths["map-detail"]), "Visible tile interrupted the required map model."
            assert len(fixture.started(paths["map-model"])) == 1
            gate.set()
            assert page.evaluate('()=>tileDemand') == len(bodies[paths["map-detail"]])
            wait_for(lambda: completed(page, fixture, manifest), "Map minimum fixture did not finish.")
            assert len(fixture.started(paths["map-model"])) == 1
            case["modelCompletedBeforeNativeTile"] = True
            case["status"] = "PASS"
            context.close()

            context, page, case, paths, bodies, manifest = setup("version")
            command(page, "start")
            wait_for(lambda: completed(page, fixture, manifest), "First manifest version did not finish.")
            command(page, "pause")
            old_version = manifest["version"]
            page.goto(origin + "/")
            page.evaluate("async ()=>{const registration=await navigator.serviceWorker.getRegistration('/fixture/');if(registration)await registration.unregister();}")
            paths, bodies, manifest = fixture.configure("version", replacement=True)
            assert manifest["version"] != old_version
            page.goto(origin + "/fixture/")
            page.evaluate(BOOT, fixture.revision)
            command(page, "pause")
            result = fetch_body(page, paths["tour"])
            assert result == {"status": 200, "bytes": len(bodies[paths["tour"]]), "sha256": sha(bodies[paths["tour"]])}, result
            assert len(fixture.started(paths["tour"])) == 2, "The new version reused the old body instead of transferring its new identity."
            case["oldVersion"] = old_version
            case["newVersion"] = manifest["version"]
            case["newBodySHA256"] = result["sha256"]
            case["manifestVersionsIsolated"] = True
            case["status"] = "PASS"
            context.close()

            context, page, case, paths, bodies, manifest = setup("refresh")
            command(page, "start")
            wait_for(lambda: completed(page, fixture, manifest), "Refresh fixture initial catalog did not finish.")
            command(page, "pause")
            old_version = manifest["version"]
            worker_before = page.evaluate('navigator.serviceWorker.controller.scriptURL')
            paths, bodies, manifest = fixture.configure("refresh", replacement=True)
            state = command(page, "start")
            assert state["version"] == manifest["version"] and state["version"] != old_version
            wait_for(lambda: completed(page, fixture, manifest), "Same-worker catalog refresh did not finish.")
            assert page.evaluate('navigator.serviceWorker.controller.scriptURL') == worker_before
            result = fetch_body(page, paths["tour"])
            assert result["sha256"] == sha(bodies[paths["tour"]])
            assert len(fixture.started(paths["tour"])) == 2
            case["catalogRefreshedWithoutWorkerReplacement"] = True
            case["status"] = "PASS"
            context.close()
            browser.close()
        report["status"] = "PASS"
    except Exception as error:
        report["status"] = "FAIL"
        report["failure"] = repr(error)
        raise
    finally:
        for gate in fixture.gates.values():
            gate.set()
        server.shutdown()
        server.server_close()
        report["httpRequests"] = fixture.snapshot()
        (out / "runtime.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf8")
        print(json.dumps({"status": report["status"], "cases": len(report["cases"]), "output": str(out)}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--saida", type=Path, default=DEFAULT_OUT)
    run(parser.parse_args().saida)
