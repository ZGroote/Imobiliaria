"""Exercise the production transfer Service Worker with small, controlled HTTP fixtures.

No Three.js scene or GPU benchmark runs here. Bodies are generated by this test;
the immutable LIV baseline is never changed and no remote resource is downloaded.
"""
from __future__ import annotations

